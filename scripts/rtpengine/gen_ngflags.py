# Generates internal/rtpengine/ngflags_gen.go: the NG protocol keys and flags
# that can appear in signalling templates (rtpengine.conf [templates], mr13.2+).
#
# Names come from the daemon sources (call_ng_main_flags, call_ng_flags_flags,
# call_ng_flags_replace, call_ng_codec_flags, with all the aliases they
# accept), descriptions from docs/ng_control_protocol.md
# (the `offer` message section).
import re, sys, os
src = sys.argv[1]; out = sys.argv[2]
branches = ["mr13.2", "mr13.3", "master"]

def func_body(txt, name):
    m = re.search(r'^[a-z][^\n(]*\b' + name + r'\(', txt, re.M)
    if not m:
        return ""
    j = txt.index('{', m.end()); depth = 0
    for k in range(j, len(txt)):
        if txt[k] == '{': depth += 1
        elif txt[k] == '}':
            depth -= 1
            if depth == 0: return txt[j:k]
    return ""

def code_names(b):
    txt = ""
    for f in (f"callif-{b}.c", f"callflags-{b}.c"):
        p = os.path.join(src, f)
        if os.path.exists(p): txt += open(p).read()
    look = lambda name: set(re.findall(r'CSH_LOOKUP\("([^"]+)"\)', func_body(txt, name)))
    return {"key": look("call_ng_main_flags"), "flag": look("call_ng_flags_flags"),
            "replace": look("call_ng_flags_replace"), "codec": look("call_ng_codec_flags")}

# sections of the offer message and the doc heading that starts each
sections = [
    ("key", "Optionally included keys are:"),
    ("flag", "**Optionally included flags are:**"),
    ("replace", "**Optionally included replace-flags are:**"),
    ("codec", "**Optionally included codec manipulations:**"),
]

def doc_entries(b):
    txt = open(os.path.join(src, f"ng-{b}.md")).read()
    start = txt.index("## `offer` Message"); end = txt.index("## `answer` Message")
    lines = txt[start:end].split("\n")
    res = {}  # (kind, name) -> paragraphs
    kind = None; names = None; body = []
    def flush():
        if kind and names:
            paras = [re.sub(r'\s+', ' ', p).strip() for p in "\n".join(body).split("\n\n")]
            paras = [p for p in paras if p]
            for n in names: res[(kind, n)] = paras
    for l in lines:
        hit = [k for k, h in sections if l.strip() == h]
        if hit:
            flush(); kind, names, body = hit[0], None, []
            continue
        if kind and l.startswith("**"):  # another block (sdp-attr…)
            flush(); kind, names, body = None, None, []
            continue
        m = re.match(r'^\* (`[^`]+`(?:\s*(?:or|,)\s*`[^`]+`)*)\s*$', l)
        if kind and m:
            flush()
            names = re.findall(r'`([^`]+)`', m.group(1)); body = []
            continue
        if names is not None:
            body.append(l)
    flush()
    return res

def norm(n): return n.replace(" ", "-")

info = {}   # (kind, name) -> paragraphs (newest branch wins)
mask = {}   # (kind, name) -> branch bits
for i, b in enumerate(branches):
    code = code_names(b)
    docs = doc_entries(b)
    found = {}
    for (kind, n), paras in docs.items():
        found[(kind, norm(n))] = paras
    for kind, names in code.items():
        for n in names:
            found.setdefault((kind, norm(n)), None)
    for k, paras in found.items():
        mask[k] = mask.get(k, 0) | (1 << i)
        if paras is not None or k not in info:
            info[k] = paras

# names known only from the code borrow the description of a documented
# spelling (case and hyphens differ: "trickle-ice" for "trickle ICE")
def loose(n): return n.lower().replace("_", "-")
docnames = {}
for (kind, n), paras in info.items():
    if paras: docnames.setdefault((kind, loose(n)), n)

def gq(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
with open(out, "w") as w:
    w.write("// Code generated by scripts/gen_ngflags.py from sipwise/rtpengine sources; DO NOT EDIT.\n\n")
    w.write("package rtpengine\n\n")
    w.write("// ngBranches are the release branches the NG flag table was extracted from.\n")
    w.write("var ngBranches = []string{" + ", ".join(gq(b) for b in branches) + "}\n\n")
    w.write("var ngSpecs = map[ngKind]map[string]ngSpec{\n")
    for kind, _ in sections:
        w.write(f"\tng{kind.capitalize()}: {{\n")
        for (k, n) in sorted(x for x in info if x[0] == kind):
            paras = info[(k, n)]
            alias = ""
            if not paras:
                alias = docnames.get((k, loose(n)), "")
                if alias == n: alias = ""
            w.write(f"\t\t{gq(n)}: {{Doc: []string{{" + ", ".join(gq(p) for p in (paras or [])) + f"}}, Alias: {gq(alias)}, Branches: 0x{mask[(k, n)]:x}}},\n")
        w.write("\t},\n")
    w.write("}\n")
for kind, _ in sections:
    names = [n for (k, n) in info if k == kind]
    print(kind, len(names), "names,", sum(1 for n in names if info[(kind, n)]), "documented")
