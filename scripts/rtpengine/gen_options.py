# Generates internal/rtpengine/options_gen.go from rtpengine sources:
# daemon/main.c + lib/auxlib.c (rtpengine) and recording-daemon/main.c + lib/auxlib.c.
import re, sys, os
src = sys.argv[1]; out = sys.argv[2]
branches = ["mr6.5","mr7.5","mr8.5","mr9.5","mr10.5","mr11.5","mr12.5","mr13.0","mr13.2","mr13.3","master"]
entry = re.compile(r'\{\s*"([a-z0-9][a-z0-9-]*)"\s*,\s*(?:\'.\'|0)\s*,\s*[^,{}]+,\s*G_OPTION_ARG_(\w+)\s*,\s*[^,{}]+,\s*((?:"(?:[^"\\]|\\.)*"\s*)+|NULL)\s*,\s*((?:"(?:[^"\\]|\\.)*"\s*)+|NULL)', re.S)
def strlit(s):
    if s.strip() == "NULL": return ""
    return "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', s)).replace('\\"','"')
def collect(files):
    res = {}
    for f in files:
        txt = open(f).read()
        for m in entry.finditer(txt):
            name, arg, desc, argd = m.group(1), m.group(2), strlit(m.group(3)), strlit(m.group(4))
            if name in ("version",): continue
            res[name] = (arg, desc, argd)
    return res
tables = {}
for kind, mainf in (("daemon","main"),("recording","rec")):
    info = {}; mask = {}
    for i, b in enumerate(branches):
        opts = collect([f"{src}/{mainf}-{b}.c", f"{src}/aux-{b}.c"])
        for n, v in opts.items():
            info[n] = v  # newest description wins
            mask[n] = mask.get(n, 0) | (1 << i)
    tables[kind] = (info, mask)
def gq(s): return '"' + s.replace('\\','\\\\').replace('"','\\"') + '"'
with open(out, "w") as w:
    w.write("// Code generated by scripts/gen_options.py from sipwise/rtpengine sources; DO NOT EDIT.\n\n")
    w.write("package rtpengine\n\n")
    w.write("// optionBranches are the release branches the option tables were extracted from.\n")
    w.write("var optionBranches = []string{" + ", ".join(gq(b) for b in branches) + "}\n\n")
    for kind, var in (("daemon","daemonOptions"),("recording","recordingOptions")):
        info, mask = tables[kind]
        w.write(f"var {var} = map[string]optionSpec{{\n")
        for n in sorted(info):
            arg, desc, argd = info[n]
            w.write(f"\t{gq(n)}: {{Arg: {gq(arg.lower())}, Desc: {gq(desc)}, Value: {gq(argd)}, Branches: 0x{mask[n]:x}}},\n")
        w.write("}\n\n")
for k,(info,mask) in tables.items():
    print(k, len(info), "options;", "in master:", sum(1 for n in mask if mask[n] >> (len(branches)-1) & 1))
